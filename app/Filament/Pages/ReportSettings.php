use Filament\Support\Icons\Heroicon;

class ReportSettings extends Page implements HasForms
{
    use InteractsWithForms;

    protected static string|BackedEnum|null $navigationIcon = Heroicon::OutlinedCog6Tooth;
    protected static string|UnitEnum|null $navigationGroup = 'Reports';
    protected static ?int $navigationSort = 0;
    protected static ?string $navigationLabel = 'Report Settings (Header/Footer, Mail)';
    protected static ?string $title = 'Report Settings — Header/Footer & Mail Formats';

    protected string $view = 'filament.pages.report-settings';

    public ?array $data = [];

    public function mount(): void
    {
        $companyName = Setting::get('company.name', config('app.name', 'Travel Company'));
        $this->data = [
            'report_header_title' => Setting::get('reports.header_title', $companyName . ' — Travel Reports'),
            'report_header_subtitle' => Setting::get('reports.header_subtitle', Setting::get('company.address', 'Kathmandu, Nepal') . ' | ' . Setting::get('company.email', 'info@example.com') . ' | ' . Setting::get('company.phone', '+977-9800000000')),
            'report_header_logo' => Setting::get('reports.header_logo', Setting::get('company.logo', '')),
            'report_footer_text' => Setting::get('reports.footer_text', 'Generated by ' . $companyName . ' — Confidential — © ' . date('Y') . ' ' . $companyName),
            'report_footer_show_page_number' => Setting::get('reports.footer_show_page_number', '1'),
            'report_company_address' => Setting::get('reports.company_address', Setting::get('company.address', 'Kathmandu, Nepal')),
            'report_primary_color' => Setting::get('reports.primary_color', Setting::get('company.primary_color', '#f59e0b')),
            'mail_booking_subject' => Setting::get('mail.booking_subject', 'Your Booking Confirmation — {{booking_code}}'),
            'mail_booking_body' => Setting::get('mail.booking_body', '<p>Dear {{customer_name}},</p><p>Your booking {{booking_code}} for {{package_title}} is confirmed.</p>'),
            'mail_inquiry_subject' => Setting::get('mail.inquiry_subject', 'Thank you for your inquiry'),
            'mail_inquiry_body' => Setting::get('mail.inquiry_body', '<p>Dear {{name}},</p><p>We received your inquiry.</p>'),
            'mail_bulk_subject' => Setting::get('mail.bulk_subject', 'Greetings from {{company_name}}'),
            'mail_bulk_body' => Setting::get('mail.bulk_body', '<p>Dear {{name}},</p><p>Check our latest packages!</p>'),
            'mail_from_name' => Setting::get('mail.from_name', $companyName),
            'mail_from_email' => Setting::get('mail.from_email', Setting::get('company.email', 'info@example.com')),
        ];
        $this->form->fill($this->data);
    }

    public function form(Schema $schema): Schema
    {
        return $schema
            ->statePath('data')
            ->components([
                Tabs::make('Report Settings Tabs')
                    ->columnSpanFull()
                    ->tabs([
                        Tab::make('Report Header/Footer')
                            ->icon('heroicon-o-document-text')
                            ->schema([
                                Section::make('Tab Information')
                                    ->icon('heroicon-o-information-circle')
                                    ->collapsible()
                                    ->schema([
                                        \Filament\Forms\Components\Placeholder::make('report_header_tab_info')
                                            ->content('This tab manages related data.')
                                            ->columnSpanFull(),
                                    ])
                                    ->columnSpanFull(),
                                Section::make('Report Header')
                                    ->description('Header on every PDF')
                                    ->columns(2)
                                    ->columnSpanFull()
                                    ->schema([
                                        TextInput::make('report_header_title')
                                            ->label('Header Title')
                                            ->placeholder('Company travel reports')
                                            ->maxLength(255)
                                            ->helperText('Company travel reports'),
                                        TextInput::make('report_primary_color')
                                            ->label('Primary Color')
                                            ->placeholder('#f59e0b')
                                            ->helperText('Header background'),
                                        TextInput::make('report_header_subtitle')
                                            ->label('Header Subtitle')
                                            ->helperText('Address | Email | Phone')
                                            ->columnSpanFull(),
                                        FileUpload::make('report_header_logo')
                                            ->label('Header Logo')
                                            ->image()
                                            ->directory('reports/header')->disk('public')->visibility('public')
                                            ->helperText('200x60 PNG')
