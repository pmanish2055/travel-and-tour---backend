                                            ->helperText('Use {{name}}, {{email}}')
                                            ->columnSpanFull(),
                                        TextInput::make('mail_from_name')
                                            ->label('From Name')
                                            ->helperText('Sender name'),
                                        TextInput::make('mail_from_email')
                                            ->label('From Email')
                                            ->email()
                                            ->helperText('Sender email'),
                                    ]),
                            ]),
                    ])            ])
            ->columns(1);
    }

    protected function getHeaderActions(): array
    {
        return [
            Action::make('save')
                ->label('Save Report Settings')
                ->color('primary')
                ->action('save'),
        ];
    }

    public function save(): void
    {
        $raw = $this->form->getState();
        $data = $raw;
        if (isset($raw['data']) && is_array($raw['data']) && !array_key_exists('report_header_title', $raw)) {
            $data = $raw['data'];
        }
        if (empty($data) && !empty($this->data)) {
            $data = array_merge($this->data, $data);
        }
        \Illuminate\Support\Facades\Log::info('ReportSettings save', ['raw' => $raw, 'resolved' => $data]);
        $map = [
            'report_header_title' => ['key' => 'reports.header_title', 'group' => 'reports'],
            'report_header_subtitle' => ['key' => 'reports.header_subtitle', 'group' => 'reports'],
            'report_header_logo' => ['key' => 'reports.header_logo', 'group' => 'reports'],
            'report_footer_text' => ['key' => 'reports.footer_text', 'group' => 'reports'],
            'report_footer_show_page_number' => ['key' => 'reports.footer_show_page_number', 'group' => 'reports'],
            'report_company_address' => ['key' => 'reports.company_address', 'group' => 'reports'],
            'report_primary_color' => ['key' => 'reports.primary_color', 'group' => 'reports'],
            'mail_booking_subject' => ['key' => 'mail.booking_subject', 'group' => 'mail'],
            'mail_booking_body' => ['key' => 'mail.booking_body', 'group' => 'mail'],
            'mail_inquiry_subject' => ['key' => 'mail.inquiry_subject', 'group' => 'mail'],
            'mail_inquiry_body' => ['key' => 'mail.inquiry_body', 'group' => 'mail'],
            'mail_bulk_subject' => ['key' => 'mail.bulk_subject', 'group' => 'mail'],
            'mail_bulk_body' => ['key' => 'mail.bulk_body', 'group' => 'mail'],
            'mail_from_name' => ['key' => 'mail.from_name', 'group' => 'mail'],
            'mail_from_email' => ['key' => 'mail.from_email', 'group' => 'mail'],
        ];
        foreach ($map as $field => $meta) {
            if (array_key_exists($field, $data)) {
                $val = $data[$field];
                if (is_array($val)) $val = json_encode($val);
                Setting::set($meta['key'], $val, $meta['group'], false);
            }
        }
        foreach (['reports','mail'] as $g) {
            \Illuminate\Support\Facades\Cache::forget('settings:'.$g);
        }
        \Illuminate\Support\Facades\Cache::forget('settings:reports+mail');
        // Refresh form state
        $saved = \App\Models\Setting::whereIn('key', array_column($map, 'key'))->pluck('value', 'key')->toArray();
        $this->data = array_merge($this->data, $data);
        foreach ($saved as $k => $v) {
            $field = array_search($k, array_column($map, 'key'));
            // Keep $this->data synced
        }
        $this->form->fill($this->data);
        \Illuminate\Support\Facades\Log::info('ReportSettings after save', $saved);
        Notification::make()->title('Report settings saved')->success()->send();
    }
}
