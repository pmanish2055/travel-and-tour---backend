                                        Textarea::make('report_footer_text')
                                            ->label('Footer Text')
                                            ->rows(2)
                                            ->helperText('Confidential footer')
                                            ->columnSpanFull(),
                                        TextInput::make('report_company_address')
                                            ->label('Company Address')
                                            ->columnSpanFull(),
                                        \Filament\Forms\Components\Toggle::make('report_footer_show_page_number')
                                            ->label('Show Page Number')
                                            ->helperText('Add Page 1 of N')
                                            ->inline(false),
                                    ]),
                            ]),

                        Tab::make('Mail Templates')
                            ->icon('heroicon-o-envelope')
                            ->schema([
                                Section::make('Tab Information')
                                    ->icon('heroicon-o-information-circle')
                                    ->collapsible()
                                    ->schema([
                                        \Filament\Forms\Components\Placeholder::make('mail_templates_tab_info')
                                            ->content('This tab manages related data.')
                                            ->columnSpanFull(),
                                    ])
                                    ->columnSpanFull(),
                                Section::make('Booking Mail')
                                    ->description('Sent on booking create')
                                    ->columnSpanFull()
                                    ->schema([
                                        TextInput::make('mail_booking_subject')
                                            ->label('Booking Subject')
                                            ->helperText('Use {{booking_code}}')
                                            ->columnSpanFull(),
                                        RichEditor::make('mail_booking_body')
                                            ->label('Booking Body')
                                            ->helperText('Use {{customer_name}} etc')
                                            ->columnSpanFull(),
                                    ]),
                                Section::make('Inquiry Mail')
